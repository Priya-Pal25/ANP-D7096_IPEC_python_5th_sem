'''Write a program to check whether a number is a natural number or not'''

#--------------------------------------------------------------------
#-----------------------Coding----------------------------------------

# Taking number from the user

num = int(input("Enter number: "))

#-----------------------------------------------------------------------

# checking whether the number is natural number or not

if (num > 0):
    print(num ,"is a Natural number")
else:
    print(num ,"is not a natural number")

#------------------------------------------------------------------------

'''Output:
Enter number: 5
5 is a Natural number
'''