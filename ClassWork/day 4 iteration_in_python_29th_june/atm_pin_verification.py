'''-------------------------------------------- ATM PIN Verification------------------------------------------ 

An ATM allows a user to enter the correct PIN. The correct PIN is 4589. The user can keep entering the 
PIN until it matches the correct one. 
Display "Access Granted" when the correct PIN is entered. 
------------------------------------------------------------------------------------------------------------
Sample Output 
Enter PIN: 1234 
Incorrect PIN 
--------------------------------------------------------------------------------------------------------------
 
Enter PIN: 9876 
Incorrect PIN 
 --------------------------------------------------------------------------------------------------------------
Enter PIN: 4589 
Access Granted 
--------------------------------------------------------------------------------------------------------------
'''

#-------------------------------------------------------------------------------------------------------------
#----------------------------------------Coding--------------------------------------------------------------

# Taking input from the user
pin = int(input("Enter four digit Correct Pin: "))

print("------------------------------------------------------------------------------------------------------")

#----------------------------------------------------------------------------------------------------------------

# Validation of pin input

if (pin <= 0):
    exit("Invalid Input! Pin must be positive")

#--------------------------------------------------------------------------------------------------------------


correct_pin = 4589


while (pin != correct_pin):
    print("Incorrect PIN")
    pin = int(input("Enter PIN: "))

print("Access Granted")

