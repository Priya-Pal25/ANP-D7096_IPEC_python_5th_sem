''' ------------------------------------Exam Hall Entry ---------------------------------------------------------

Students are allowed to enter the examination hall only if they are carrying their admit card. 
Accept input as: 
• 1 → Admit Card Available  
• 0 → Admit Card Not Available  
----------------------------------------------------------------------------------------------------------------
If the input is 1, display: 
Enter Examination Hall 
Otherwise, do not display anything. 
---------------------------------------------------------------------------------------------------------------
Sample Input 
1 
---------------------------------------------------------------------------------------------------------------
Sample Output 
Enter Examination Hall
--------------------------------------------------------------------------------------------------------------
'''
#-------------------------------------------------------------------------------------------------------------
#--------------------------------------------Coding-----------------------------------------------------------

# Taking admit card input from the user

admit_card = int(input("Enter the admit card input (0 or 1): " ))

print("---------------------------------------------------------------------------------------------------------")

#----------------------------------------------------------------------------------------------------------------

# validating admit_card input

if (admit_card < 0 or admit_card > 1):
    exit("Invalid Input")

#----------------------------------------------------------------------------------------------------------------

# displaying the result and checking if the student is allowed to enter the examination hall or not

if (admit_card == 1):
    print("Enter Examination Hall ")

#------------------------------------------------------------------------------------------------------------

'''Output:
Enter the admit card input (0 or 1): 1
---------------------------------------------------------------------------------------------------------
Enter Examination Hall 
'''

