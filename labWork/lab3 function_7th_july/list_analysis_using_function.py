'''------------------------------------------------- List Analysis using Functions-----------------------------------------------
Write a Python program that defines the following functions: 
• find_max(numbers)  
• find_min(numbers)  
• find_average(numbers)  
The program should: 
• Accept a list of 10 integers from the user.  
• Call all three functions.  
• Display the maximum value, minimum value, and average of the list. 
'''

#----------------------------------------------------------------------------------------------------------------------------------
#----------------------------------------------Coding-------------------------------------------------------------------------------

# function to find maximum of number
def find_max(numbers):
    return max(numbers)

#--------------------------------------------------------------------------------------------------------------
# function to find minimum of number

def find_min(numbers):
    return min(numbers)
#--------------------------------------------------------------------------------------------------------------

# function to find average of numbers 
def find_average(numbers):
    return (sum (numbers)/len(numbers))

#----------------------------------------------------------------------------------------------------------------

# main program

# creating blank list
numbers = []
print("Enter any 10 numbers")
for i in range(10):
    # taking input from the user
    num = int(input())
    numbers.append(num)

# displaying list of numbers
print("Numbers are : " , numbers)

print("-----------------------------------------------------------------------------------------")
#-----------------------------------------------------------------------------------------------

# displaying maximum value
print("Maximum Value : " , find_max(numbers))
print("-----------------------------------------------------------------------------------------")

#------------------------------------------------------------------------------------------------

# displaying minimum value
print("Minimum value : " , find_min(numbers))
print("-------------------------------------------------------------------------------------------")

#--------------------------------------------------------------------------------------------------

# displaying average value
print("Average value: " , find_average(numbers))
print("----------------------------------------------------------------------------------------------")

